// Справочник материалов: картон (шероховатость и фактура по типу бумаги) и
// пластик. Это единственное место, куда дописываются новые типы — логика
// вьювера сюда не заглядывает.
//
// МОДЕЛИ СТАКАНОВ ЗДЕСЬ БОЛЬШЕ НЕ ЛЕЖАТ: их каталог — js/data/models.js, туда же
// дописываются новые позиции номенклатуры.

// ── Картон ────────────────────────────────────────────────────────────────
// ЗДЕСЬ НАСТРАИВАЕТСЯ ВНЕШНИЙ ВИД КАРТОНА. Три числа на тип, все уходят в
// материал меша под дизайном (см. Viewer.setSurfaceFinish).
//
//   roughness — как собран блик. 0 — зеркало, 1 — полностью матовая.
//       Мелованный лощёный отражает собранно, немелованный впитывает свет и
//       рассеивает его.
//
//   relief — сила фактуры («рябь»): микрорельеф волокна, из-за которого блик
//       чуть дрожит. 0 — идеально гладко, 0.5 — грубая крафт-бумага.
//       У мелованного поверх волокна лежит меловой слой и каландрирование,
//       поэтому рельефа почти нет; у немелованного волокно открыто.
//
//   reliefScale — крупность зерна: сколько раз рисунок волокна укладывается по
//       стенке. БОЛЬШЕ ЗНАЧЕНИЕ — МЕЛЬЧЕ зерно. У мелованного зерно тоньше.
//
// Подобрать вживую, не пересобирая: см. cupViewer.setRelief() в README.
//
// Картон — не металл, поэтому metalness одинаков для всех типов и в справочнике
// не повторяется.
export const PAPER_METALNESS = 0;

export const PAPER_TYPES = {
  coated: {
    label: 'Мелованный',
    // 0.2 — это почти зеркало: стенка ловила отражение всей студии, и чёрная
    // заливка выходила серой. У лакированного картона блик собранный, но не
    // зеркальный; 0.4 держит и глянец, и цвет.
    roughness: 0.4,
    relief: 0.009,
    reliefScale: 90,
  },
  uncoated: {
    label: 'Немелованный',
    roughness: 0.8,
    relief: 0.1,
    reliefScale: 10,
  },
};

// КАКОЙ КАРТОН ПОКАЗЫВАТЬ, ПОКА ЗАКАЗ НЕ СКАЗАЛ ИНОГО.
//
// Это единственное место, где задан картон по умолчанию: отсюда его берёт и
// DEFAULT_ORDER (js/data/order.js), и запасная отделка при загрузке модели.
// Поменяйте на 'coated' — страница откроется мелованной.
export const DEFAULT_PAPER = 'uncoated';

// Отделка «по умолчанию» одним объектом — тем же, что уходит в материал.
// Нужна на момент, когда модель уже загрузилась, а заказ ещё не применён.
export function defaultPaperFinish() {
  const paper = PAPER_TYPES[DEFAULT_PAPER];
  return {
    roughness: paper.roughness,
    metalness: PAPER_METALNESS,
    relief: paper.relief,
    reliefScale: paper.reliefScale,
  };
}

// ── Пластик ───────────────────────────────────────────────────────────────
// Молочный полипропилен. Ставится моделям с finish: 'plastic'
// (js/data/models.js) и НЕ зависит от заказа: тип бумаги к пластиковому
// стакану отношения не имеет.
//
// ── Почему стенка полупрозрачна через ПРОЗРАЧНОСТЬ, а не через «стекло» ──
//
// В файле модели стенка описана как стекло: KHR_materials_transmission со
// значением 0.95. В Blender это работает, потому что молочность там живёт не в
// поверхности, а в объёмном рассеянии внутри стенки — свет входит, путается в
// толще и выходит рассеянным. В браузере такого нет: three.js умеет только
// поглощение по расстоянию, то есть «цветное стекло», но не «молоко».
//
// Хуже того, сквозь transmission видно ТОЛЬКО фон: сам предмет в буфер
// преломления не попадает. Стакан превращался в окно — на белом фоне исчезал
// целиком, а при наклоне камеры от него оставалась одна тень. Проверено:
// с transmission на светлом фоне в кадре нет ничего, кроме тени.
//
// Поэтому стенка полупрозрачна обычным альфа-смешением. Сквозь неё видно то,
// что и должно быть видно, — противоположную стенку, дно и рёбра расстыковки
// (их рисует второй проход по задним граням, см. ModelLoader). Именно по ним
// глаз и узнаёт молочный пластик, а не по размытому фону. Заодно это дешевле:
// transmission заставляет three рендерить сцену второй раз в отдельный буфер.
//
// ЦВЕТ СТЕНКИ БЕЛЫЙ. Он умножается на макет, и любая подкраска стенки — это
// подкраска печати: в файле модели стоит 0.88, то есть каждый цвет макета
// терял бы 12 % яркости. Молочность делает прозрачность, а не оттенок.
export const PLASTIC_FINISH = Object.freeze({
  color: '#ffffff',

  // Насколько плотна НЕЗАПЕЧАТАННАЯ стенка. 1 — глухая, 0 — стекло.
  //
  // Печати это НЕ касается: она кроющая и остаётся непрозрачной (альфа
  // приходит вместе с макетом, см. js/loaders/TextureManager.js). Иначе цвет
  // печати зависел бы от фона, а страница существует ради согласования цвета.
  //
  // Значение выверено по фотографиям изделия (3D_plast/ref): молочный
  // полипропилен РАССЕИВАЕТ свет, а не пропускает изображение. Сквозь стенку
  // видно, что за ней светлее или темнее, но не видно ЧТО именно — ни дна, ни
  // клейма на нём.
  opacity: 0.65,

  // Литой PP матовый, но не бумага: блик рассеян шире картонного.
  roughness: 0.62,
  metalness: 0,

  // Глянцевая плёнка поверх матовой стенки — то, чем литой пластик отличается
  // от бумаги на просвет: сама стенка мутная, а поверхность бликует.
  clearcoat: 0.35,
  clearcoatRoughness: 0.3,

  // Мягкая подсветка по краям. В three это «ворс» для тканей, но считается он
  // ровно тем, чего здесь не хватает: светом, ушедшим в материал и вышедшим
  // обратно под скользящим углом. На силуэте стакана он и даёт молочность.
  sheen: 0.5,
  sheenRoughness: 0.6,
});

// Синонимы: Битрикс может прислать что угодно из этого списка.
const PAPER_ALIASES = {
  coated: 'coated',
  мелованный: 'coated',
  мелованная: 'coated',
  глянцевый: 'coated',
  uncoated: 'uncoated',
  немелованный: 'uncoated',
  немелованная: 'uncoated',
  крафт: 'uncoated',
  матовый: 'uncoated',
};

// Тип картона → { key, label, roughness }. Принимает и ключ, и русское название.
export function resolvePaper(paper) {
  const raw = String(paper ?? '').trim().toLowerCase();
  const key = PAPER_ALIASES[raw] ?? (PAPER_TYPES[raw] ? raw : DEFAULT_PAPER);
  return { key, ...PAPER_TYPES[key] };
}
