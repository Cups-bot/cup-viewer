//      останется без тени вовсе, но она заметно грубее снятой.
// Больше нигде ничего править не нужно: ни разметку, ни стили, ни вьювер.
//
// ── Что нужно от самого файла ─────────────────────────────────────────────
// Размер и единицы не важны: модель всё равно нормализуется к
// config.model.targetSize и ставится на пол по нижней точке. Важно другое:
//
//   • печатная стенка — ОТДЕЛЬНЫЙ материал. По имени этого материала
//     просмотрщик и находит, куда класть макет (поле print.materials);
//   • сглаженные нормали и не меньше 256 сегментов по окружности, иначе на
//     блике видны грани;
//   • модель со сжатием Draco открывается как есть — распаковщик лежит в
//     vendor/draco/;
//   • в файле ОДИН стакан. Высоту берут не из файла, а отсюда, из size.height,
//     — и просмотрщик, и съёмка тени; но лишние предметы попадут и в кадр, и
//     в тень.

