// Каталог фото-сцен — снятых фонов, в которые ставится стакан.
//
// ЭТО ЕДИНСТВЕННОЕ МЕСТО, КУДА ДОПИСЫВАЕТСЯ НОВАЯ СЦЕНА. Всё остальное про неё
// лежит рядом с её файлами: камера, пол и масштаб приходят из scene.json,
// который пишет экспортёр (3D_plast/mockup/tools/export_web_scene.py).
//
// ── Как добавить сцену ────────────────────────────────────────────────────
//   1. Добавьте фон в 3D_plast/mockup/sets и впишите его имя в WEB_SETS
//      экспортёра.
//   2. blender -b -P tools/export_web_scene.py -- --set <имя>
//   3. Снимите тени всех стаканов: --catalog-shadows (без них стакан
//      встанет на снимок с расчётной тенью, а она заметно грубее снятой).
//   4. Допишите сюда строчку. npm run build.
//
// Со второй сцены на странице появляется ряд кнопок выбора: одна кнопка,
// которую некуда переключить, была бы лишним элементом.
//
// Подписи здесь — клиентские: их видит тот, кто согласовывает макет, поэтому
// они говорят о свете, а не о том, из какого файла взята сцена.

export const PHOTO_SCENES = Object.freeze([
  {
    id: 'cafe',
    label: 'Кофейня',
    note: 'Утренний свет из окна',
  },
]);

// Папка со сценами. Внутри — по папке на сцену: backdrop.webp,
// backdrop-tall.webp, env.hdr, scene.json.
export const SCENES_ROOT = 'assets/scenes';

// С какой сцены открывается вкладка — с первой в каталоге.
export const DEFAULT_SCENE_ID = PHOTO_SCENES[0].id;

export function findScene(id) {
  return PHOTO_SCENES.find((scene) => scene.id === id) ?? null;
}
