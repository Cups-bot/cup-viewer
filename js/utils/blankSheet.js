// Пустой лист А4 — то, что ложится на стакан, когда своего макета ещё нет.
//
// ЗАЧЕМ. Во-первых, при смене модели прежний макет на новую НЕ переносится. У
// каждого стакана своя развёртка: та же картинка на соседней модели съезжает,
// растёт или обрезается — и клиент принимает это за брак печати, хотя виноват
// просмотр. Поэтому новая модель приезжает с чистым листом, а дизайн кладётся на
// неё уже осознанно — кнопкой «Заменить дизайн» или данными заказа.
//
// Во-вторых, тот же лист лежит на стакане, пока заказ не сказал, что печатать.
// Оставить картинку из файла модели нельзя: у бумажных стаканов там техническая
// развёртка с метками вырубки и чужими логотипами, и клиент принимает её за
// свой макет.
//
// ПОЧЕМУ НЕ ФАЙЛОМ В assets/. Ровная белая заливка — это несколько килобайт,
// которые пришлось бы выкладывать вместе с сайтом, версионировать и ждать по
// сети. Проще нарисовать.

// Пропорции листа: 297 × 210 мм. Лежачий, а не стоячий: развёртка стакана
// всегда шире, чем выше, и на вкладке «Развёртка» стоячий лист смотрелся бы
// чужеродно. Поменять ориентацию — поменять местами два числа.
const SHEET_MM = { width: 297, height: 210 };

// Пикселей по длинной стороне. Разглядывать на пустом листе нечего, поэтому
// берём немного: лист попадает и в видеопамять (как текстура модели), и в
// развёртку. 1024 × 724 — это 3 МБ распакованного растра вместо 12 МБ у 2048.
const SHEET_WIDTH = 1024;

let cached = null;

// Адрес листа (data:-URL). Один и тот же и для модели, и для вкладки
// «Развёртка», поэтому считается один раз за жизнь страницы.
export function blankSheetUrl() {
  if (cached) return cached;

  const canvas = document.createElement('canvas');
  canvas.width = SHEET_WIDTH;
  canvas.height = Math.round((SHEET_WIDTH * SHEET_MM.height) / SHEET_MM.width);

  const ctx = canvas.getContext('2d');
  // Чистый белый, без подложек и рамок: это бумага, а не элемент интерфейса.
  ctx.fillStyle = '#ffffff';
  ctx.fillRect(0, 0, canvas.width, canvas.height);

  cached = canvas.toDataURL('image/png');
  return cached;
}
