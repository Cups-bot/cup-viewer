//
// Фон ставит Viewer.selectBackground — и в сцену, и в CSS страницы, одним и
// тем же цветом.
//
// Когда-то фон был только в CSS, а холст прозрачным: тонмаппинг применяется
// последним проходом ко всему кадру вместе с заливкой, и светло-голубой
// #eaf5ff после ACES превращался в невнятный серый. Тонмаппинг выключен ради
// цветопередачи (см. config.renderer.toneMapping), поэтому причина отпала, а
// прозрачный холст создавал свою проблему: на сглаженных краях полупрозрачный
// пиксель после перевода в sRGB раздувается. Из-за этого по краю пола шла
// светлая волосяная линия — горизонт, которого не должно быть видно.
//
// ВНИМАНИЕ: если когда-нибудь вернёте тонмаппинг, фон снова начнёт менять
// цвет. Тогда его придётся выносить обратно в CSS.
