import * as THREE from 'three';

// Корневая сцена.
//
// Фон ставит Viewer.selectBackground — и в сцену, и в CSS страницы, из одного
// набора цветов (см. core/backdrop.js). В сцене это заливка плюс свёртка —
// прямоугольник со слабой растяжкой по высоте, прибитый к камере.
//
// Когда-то фон был только в CSS, а холст прозрачным: тонмаппинг применяется
// последним проходом ко всему кадру вместе с заливкой, и светло-голубой
// #eaf5ff после ACES превращался в невнятный серый. Тонмаппинг выключен ради
// цветопередачи (см. config.renderer.toneMapping), поэтому причина отпала, а
// прозрачный холст создавал свою проблему: на сглаженных краях полупрозрачный
// пиксель после перевода в sRGB раздувается, и по краю шла светлая волосяная
// линия.
//
// ВНИМАНИЕ: если когда-нибудь вернёте тонмаппинг, фон снова начнёт менять
// цвет. Тогда свёртку придётся класть отдельным проходом, уже после него, —
// ровно так, как это делает фото-сцена (см. core/postprocessing.js).
