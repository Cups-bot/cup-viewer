// Слои отрисовки.
//
// Слой 0 — сам предмет: всё, что клиент считает «стаканом».
// Слой 1 — вспомогательная обвязка: плоскость тени и поворотный круг. Это
// элементы интерфейса, нарисованные внутри 3D-сцены.
//
// Разделение нужно постобработке: затенение складок (AO) считается по глубине и
// нормалям, и если в этот расчёт попадёт плоскость тени, вокруг стакана по фону
// расползётся тёмное кольцо, а поворотный круг оставит на полу грязный след.
// Основная камера видит оба слоя, камера AO — только нулевой.
//
// Внимание: Raycaster по умолчанию тоже видит только слой 0. Всё, по чему нужно
// попадать курсором и что живёт на слое 1, обязано включить этот слой своему
// лучу (см. core/turntable.js).
// Основная камера видит слои 0 и 1, камера затенения складок — только слой 0:
// плоскости теней и поворотный круг в расчёте затенения участвовать не должны,
// иначе они обводят стакан тёмным кольцом.
export const OBJECT_LAYER = 0;
export const HELPER_LAYER = 1;
