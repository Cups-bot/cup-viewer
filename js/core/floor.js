import * as THREE from 'three';
import { OBJECT_LAYER } from './layers.js';

// Поверхность, на которой стоит стакан.
//
// ЗАЧЕМ ОНА ВООБЩЕ НУЖНА, если её не видно. Затенение у контакта — это не
// эффект, а следствие геометрии: рядом с основанием подложка загорожена
// стаканом и потому темнеет. Считать это можно только по настоящей
// поверхности. Пока её не было, расчёт затенения работал по невидимой
// вспомогательной плоскости, а она не рисуется в кадр — значит у тех пикселей
// нулевая прозрачность, и умножать затенению было нечего. Стык приходилось
// подделывать размытым пятном, и он каждый раз выглядел наклеенным.
//
// ПОЧЕМУ ЕЁ НЕ ВИДНО. Материал не реагирует на свет, а цвет ему ставится ровно
// тот же, что у фона страницы. Тонмаппинг выключен (см. config.renderer), так
// что цвет доезжает до экрана без искажений и пол сливается с фоном пиксель в
// пиксель. Горизонта не видно по той же причине.
//
// Побочная выгода: тени и затенение теперь смешиваются с непрозрачной
// поверхностью ДО перевода в sRGB. При прозрачном холсте светлые полупрозрачные
// элементы после перевода раздувались — из-за этого, в частности, не получалось
// отражение.
export function createFloor(config) {
  const options = config.floor;

  const material = new THREE.MeshBasicMaterial({
    color: 0xffffff,
    // Свет на пол не влияет: он обязан совпасть с фоном страницы, а не быть
    // «освещённым».
    fog: false,
  });

  const mesh = new THREE.Mesh(new THREE.PlaneGeometry(options.size, options.size), material);
  mesh.rotation.x = -Math.PI / 2;
  mesh.name = 'Floor';
  // Виден и основной камере, и расчёту затенения складок — в этом весь смысл.
  mesh.layers.set(OBJECT_LAYER);

  // …но НЕ проходу глубины, которым считается затенение у основания
  // (core/ambientContactShadow.js): тот снимает сцену ортокамерой снизу вверх,
  // и пол оказался бы ровно на её нулевой плоскости отсчёта. Сейчас он и так
  // отсекается как обращённый к камере изнанкой, но полагаться на это не стоит:
  // затенять сам себя полу всё равно нечем.
  mesh.userData.excludeFromShadow = true;
  // Рисуется раньше всего: тени и затенение ложатся поверх.
  mesh.renderOrder = -3;

  return {
    mesh,

    // Цвет берётся из выбранного фона страницы — они обязаны совпадать
    // пиксель в пиксель, иначе проступает горизонт.
    //
    // Никаких ручных конверсий: three сам переводит переданный цвет из sRGB в
    // рабочее линейное пространство, а обратно его переводит OutputPass в конце
    // конвейера. Добавленный сюда convertSRGBToLinear() давал вторую конверсию,
    // и пол выходил темнее фона на полтора десятка единиц.
    setColor(value) {
      material.color.set(value);
    },

    // Чуть НИЖЕ плоскостей теней. Они лежат на уровне основания и глубину не
    // пишут, но по глубине пола тестируются. На совпадающих высотах результат
    // сравнения неустойчив, и при облёте камерой тени мигали от кадра к кадру —
    // классическое z-fighting. Полутора тысячных достаточно, и пол всё равно
    // не виден.
    setHeight(y) {
      mesh.position.y = y - 0.0015;
    },

    dispose() {
      mesh.geometry.dispose();
      material.dispose();
      mesh.removeFromParent();
    },
  };
}
