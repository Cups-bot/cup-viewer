import * as THREE from 'three';
import { HELPER_LAYER } from './layers.js';

// Поверхность, на которой стоит стакан.
//
// ЗАЧЕМ ОНА НУЖНА, если её не видно: чтобы кадр под стаканом был НЕПРОЗРАЧНЫМ.
//
// Перевод в sRGB идёт последним проходом, уже после смешивания. Полупрозрачный
// пиксель хранится как цвет, умноженный на прозрачность, и нелинейный перевод
// рвёт эту связь — пиксель становится светлее, чем должен. На чёрном это
// незаметно (ноль остаётся нулём), поэтому тени работали. А вот на сглаженных
// краях выступало: по кадру шла светлая волосяная линия. По той же причине не
// получалось отражение в подложке.
//
// ПОЧЕМУ ЕЁ НЕ ВИДНО. Материал не реагирует на свет, а цвет ему ставится ровно
// тот же, что у фона сцены. Тонмаппинг выключен (см. config.renderer), так что
// цвет доезжает до экрана без искажений и пол сливается с фоном пиксель в
// пиксель.
export function createFloor(config) {
  const options = config.floor;

  const material = new THREE.MeshBasicMaterial({
    color: 0xffffff,
    // Свет на пол не влияет: он обязан совпасть с фоном сцены, а не быть
    // «освещённым».
    fog: false,
    // Глубину НЕ пишет. Иначе пол срезает всё, что лежит на нём же: метка
    // поворотного круга наполовину уходила под поверхность. Затенению складок
    // это не мешает — оно рендерит собственную глубину отдельным проходом, а
    // не читает основную.
    depthWrite: false,
  });

  const mesh = new THREE.Mesh(new THREE.PlaneGeometry(options.size, options.size), material);
  mesh.rotation.x = -Math.PI / 2;
  mesh.name = 'Floor';
  // Слой обвязки: пол видит основная камера, но НЕ видит расчёт затенения
  // складок.
  //
  // Затенение работает по глубине, и дальний край пола оно принимает за границу
  // перекрытия — по кадру шла бледная горизонтальная полоса на уровне горизонта,
  // заметная под низкими ракурсами. Потерять при этом нечего: на рабочем радиусе
  // (0.07) затенение давало на полу 240 против 243 фона, то есть почти ничего,
  // а видимый стык держится на отдельном слое (core/ambientContactShadow.js).
  mesh.layers.set(HELPER_LAYER);

  // И не участвует в проходе глубины, которым считается затенение у основания:
  // тот снимает сцену ортокамерой снизу вверх, и пол оказался бы ровно на её
  // нулевой плоскости отсчёта. Затенять сам себя полу всё равно нечем.
  mesh.userData.excludeFromShadow = true;
  // Рисуется раньше всего: тени и затенение ложатся поверх.
  mesh.renderOrder = -3;

  return {
    mesh,

    // Цвет берётся из выбранного фона страницы — они обязаны совпадать
    // пиксель в пиксель, иначе проступает горизонт.
    //
    // Никаких ручных конверсий: three сам переводит переданный цвет из sRGB в
    // рабочее линейное пространство, а обратно его переводит OutputPass в конце
    // конвейера. Добавленный сюда convertSRGBToLinear() давал вторую конверсию,
    // и пол выходил темнее фона на полтора десятка единиц.
    setColor(value) {
      material.color.set(value);
    },

    // Чуть ниже плоскостей теней — порядок рисования задаётся renderOrder, но
    // разводить их и по высоте дешевле, чем разбираться, почему они спорят.
    setHeight(y) {
      mesh.position.y = y - 0.0015;
    },

    dispose() {
      mesh.geometry.dispose();
      material.dispose();
      mesh.removeFromParent();
    },
  };
}
